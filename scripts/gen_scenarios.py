"""Expand every data/scenarios/*/script*.md into its thread/email file with GENERATE_MODEL. Idempotent: an existing output is never touched.

A script starts with header lines `key: value` up to the first blank line:
  output: thread.json | email.txt | none     channel: teams | email     date: YYYY-MM-DD
  email only: from: <name>   to: <name or list>
The rest of the file is the scenario script sent to the model.
"""
import json
import sys
from pathlib import Path
from typing import Literal

from pydantic import BaseModel, Field

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
import llm  # noqa: E402

SCENARIOS = ROOT / "data" / "scenarios"

SYSTEM = """You write synthetic but realistic workplace conversations between telecom network field engineers and network experts in Finland, for testing a knowledge-capture system.
Follow the scenario script exactly: the speakers, the device IDs (copy them exactly as the script writes them, including any deliberate typos), the hidden rule, the trap and the outcome.
Hard rules:
- Use only the names and device/site IDs given in the script. Never invent other devices, sites, customers, companies or people.
- Never write ticket numbers, case numbers, incident IDs or order numbers of any kind.
- No real company names, no phone numbers, no e-mail addresses.
- Language: plain, slightly informal technical English as written by Finnish engineers.
Teams style: short chat messages, 1-3 sentences each, times as HH:MM increasing through the conversation, a typo or a smiley here and there (not in every message).
Email style: one message, a short subject line, a greeting, a few short paragraphs, a sign-off with the sender's first name."""


class TeamsMessage(BaseModel):
    time: str = Field(description="HH:MM, 24-hour, increasing through the thread")
    author: str = Field(description="Full name of the speaker, exactly as in the script")
    role: Literal["Field Engineer", "Network Expert"] = Field(description="The speaker's role, exactly as in the script")
    text: str = Field(description="The chat message text")


class TeamsThread(BaseModel):
    messages: list[TeamsMessage] = Field(description="The chat messages in order")


class Email(BaseModel):
    subject: str = Field(description="The subject line, without the 'Subject:' prefix")
    body: str = Field(description="The email body: greeting, paragraphs, sign-off")


def parse_script(path: Path) -> tuple[dict, str]:
    head, _, body = path.read_text(encoding="utf-8").partition("\n\n")
    meta = dict(line.split(":", 1) for line in head.splitlines())
    return {k.strip(): v.strip() for k, v in meta.items()}, body.strip()


def render_teams(thread: TeamsThread, meta: dict, script: Path) -> str:
    seen = {}
    for m in thread.messages:
        seen.setdefault(m.author, m.role)
    doc = {
        "channel": "teams",
        "note": f"Synthetic placeholder generated by {llm.GENERATE_MODEL} from {script.relative_to(ROOT).as_posix()}. Names and node IDs are illustrative.",
        "date": meta["date"],
        "placeholder": True,
        "participants": [{"name": n, "role": r} for n, r in seen.items()],
        "messages": [{"seq": i, "time": m.time, "author": m.author, "role": m.role, "text": m.text}
                     for i, m in enumerate(thread.messages, 1)],
    }
    return json.dumps(doc, indent=2, ensure_ascii=False) + "\n"


def render_email(mail: Email, meta: dict) -> str:
    return (f"From: {meta['from']}\nTo: {meta['to']}\nSubject: {mail.subject.strip()}\nDate: {meta['date']}\n\n"
            f"{mail.body.strip()}\n")


def main() -> None:
    for script in sorted(SCENARIOS.glob("*/script*.md")):
        meta, body = parse_script(script)
        if meta["output"] == "none":  # incident-only scenario, nothing to generate
            continue
        out = script.parent / meta["output"]
        if out.exists():
            print(f"skip {out.relative_to(ROOT).as_posix()} (exists)")
            continue
        user = f"Channel: {meta['channel']}\nDate: {meta['date']}\n\nScenario script:\n{body}"
        if meta["channel"] == "teams":
            text = render_teams(llm.structured(SYSTEM, user, TeamsThread, model=llm.GENERATE_MODEL), meta, script)
        else:
            text = render_email(llm.structured(SYSTEM, user, Email, model=llm.GENERATE_MODEL), meta)
        out.write_text(text, encoding="utf-8")
        print(f"wrote {out.relative_to(ROOT).as_posix()}")


if __name__ == "__main__":
    main()
