"""docs/CASE_TABLE.md (one row per scenario, then every check) and docs/case_table.json (raw results)."""
import json
from dataclasses import asdict
from pathlib import Path

from pipeline import ROOT


def _cell(s) -> str:
    return str(s).replace("|", "\\|").replace("\n", " ")


def write_case_table(results, path=ROOT / "docs" / "CASE_TABLE.md") -> None:
    path = Path(path)
    lines = ["# Case table", "", "Generated by `eval/` (`py -3.14 -m eval.runner` or `pytest eval`). "
             "A scenario fails if any of its checks fails.", "",
             "| # | scenario | trap | lane | result | why |", "|---|---|---|---|---|---|"]
    for i, r in enumerate(results, 1):
        failed = [(n, w) for n, ok, w in r.checks if not ok]
        why = "; ".join(f"{n}: {w}" for n, w in failed) if failed else f"{len(r.checks)} checks pass"
        lines.append(f"| {i} | {r.scenario} | {_cell(r.trap)} | {r.lane} | {'pass' if r.passed else 'FAIL'} | {_cell(why)} |")
    lines += ["", "## Every check", "", "| scenario | check | result | why |", "|---|---|---|---|"]
    for r in results:
        lines += [f"| {r.scenario} | {_cell(n)} | {'pass' if ok else 'FAIL'} | {_cell(w)} |" for n, ok, w in r.checks]
    checks = [ok for r in results for _, ok, _ in r.checks]
    lines += ["", "## Totals", "",
              f"- Scenarios: {sum(r.passed for r in results)}/{len(results)} pass",
              f"- Checks: {sum(checks)}/{len(checks)} pass", "",
              "## Placeholder data", "",
              "Inputs of scenarios marked `placeholder: true` (generated threads, to be replaced by Abhishek's scripts; "
              "see `data/DATA_CARD.md`):", ""]
    lines += [f"- {r.scenario}: {', '.join(f'`{p}`' for p in r.inputs) or '(no inputs of its own)'}"
              for r in results if r.placeholder]
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    raw = [{**asdict(r), "passed": r.passed, "checks": [{"name": n, "passed": ok, "why": w} for n, ok, w in r.checks]}
           for r in results]
    path.with_name("case_table.json").write_text(json.dumps(raw, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
